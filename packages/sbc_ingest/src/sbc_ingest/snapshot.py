"""Corpus snapshot: SBC counts per portal, state and market, and a fingerprint of the SBC ID list.

The catalog itself stays under the uncommitted ``data/`` folder, so a later run had nothing to compare against
when the portal changed. This writes a small Markdown file (metadata only, no SBC text) that is committed, so
the next run can show which counts moved. The fingerprint tells whether the set of SBC IDs changed; naming the
exact documents still needs the earlier catalog.

Usage: ``sbc-snapshot [--year 2027] [--out docs/reviews/corpus-snapshot-2027.md]``
"""

from __future__ import annotations

import argparse
import csv
import hashlib
from collections import Counter
from pathlib import Path

from sbc_ingest.paths import ROOT


def snapshot(rows: list[dict[str, str]], year: str) -> str:
    ids = sorted(r["sbc_id"] for r in rows)
    fingerprint = hashlib.sha256("\n".join(ids).encode()).hexdigest()
    portals = Counter(r["portal"] for r in rows)
    markets = Counter(r["market_unit"] for r in rows)
    by_state: dict[str, Counter[str]] = {}
    for r in rows:
        by_state.setdefault(r["state"], Counter())[r["market_unit"]] += 1
    columns = sorted(markets, key=lambda m: -markets[m])
    lines = [
        f"# Corpus snapshot: {year} SBCs",
        "",
        f"Generated by `sbc-snapshot` from `data/catalog/sbc_catalog_{year}.csv`. Metadata only.",
        "Compare with a fresh run to see which counts moved; the fingerprint is the sha256 of the sorted",
        "SBC IDs, one per line.",
        "",
        f"- SBCs: **{len(rows):,}**",
        "- Portals: " + ", ".join(f"{p} {n:,}" for p, n in sorted(portals.items())),
        "- Markets: " + ", ".join(f"{m} {markets[m]:,}" for m in columns),
        f"- SBC ID fingerprint: `{fingerprint}`",
        "",
        "| State | " + " | ".join(columns) + " | Total |",
        "|---|" + "---:|" * (len(columns) + 1),
    ]
    for state in sorted(by_state):
        counts = by_state[state]
        cells = " | ".join(str(counts[m]) if counts[m] else "" for m in columns)
        lines.append(f"| {state} | {cells} | {sum(counts.values())} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="Write the corpus count snapshot.")
    ap.add_argument("--year", default="2027")
    ap.add_argument("--out", type=Path)
    args = ap.parse_args(argv)
    catalog = ROOT / "data" / "catalog" / f"sbc_catalog_{args.year}.csv"
    with catalog.open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    out = args.out or ROOT / "docs" / "reviews" / f"corpus-snapshot-{args.year}.md"
    out.write_text(snapshot(rows, args.year), encoding="utf-8")
    print(f"{out}: {len(rows)} SBCs")
